HELP_SECTIONS_BY_ID = {section["id"]: section for section in HELP_SECTIONS}


def _normalize(text: str) -> str:
    return " ".join(str(text or "").lower().split())


def _score(section: dict, query: str) -> int:
    title = _normalize(section["title"])
    score = 0
    if query in title or title in query:
        score += 3
    for keyword in section["keywords"]:
        word = _normalize(keyword)
        if not word:
            continue
        if word == query:
            score += 3
        elif word in query or (len(query) >= 2 and query in word):
            score += 2
    return score


def _index_answer() -> str:
    lines = [HELP_SECTIONS_BY_ID[QUICK_REFERENCE_ID]["body"], "### 全部帮助主题"]
    lines.extend(
        f"- {section['title']}"
        for section in HELP_SECTIONS
        if section["id"] != QUICK_REFERENCE_ID
    )
    return "\n\n".join(lines)


def find_help(query: str) -> dict:
    normalized = _normalize(query)
    if not normalized:
        return {"answer": _index_answer(), "sections": [QUICK_REFERENCE_ID], "matched": False}

    scored = [
        (_score(section, normalized), index, section)
        for index, section in enumerate(HELP_SECTIONS)
        if section["id"] != QUICK_REFERENCE_ID
    ]
    hits = sorted(
        (item for item in scored if item[0] > 0),
        key=lambda item: (-item[0], item[1]),
    )[:3]

    if not hits:
        return {"answer": _index_answer(), "sections": [QUICK_REFERENCE_ID], "matched": False}

    hits.sort(key=lambda item: item[1])
    answer = "\n\n---\n\n".join(section["body"] for _, _, section in hits)
    return {
        "answer": answer,
        "sections": [section["id"] for _, _, section in hits],
        "matched": True,
    }


