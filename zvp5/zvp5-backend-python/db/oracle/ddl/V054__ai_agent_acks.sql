-- 在 V001~V053 已应用的实例上补齐 AI_AGENT_ACKS（「AI Agent 首次使用安全警示
-- 已确认」，跟着帐号走，替代客户端 localStorage）。
--
-- 为什么要有这张表：
--   * 警示内容说的是「Agent 会替你执行写操作，请确认你理解风险」，这是一个
--     **账号级**的知情确认，不是设备偏好。放 localStorage 的话，换设备/清缓存/
--     重装就会重弹，用户也可能在另一台设备上「确认过又反悔」。
--   * 空表 = 未确认：没有行就是「这个人还没点头」，不需要额外的 bool 列。
--   * 不做历史流水：确认只发生一次，重复调用不刷新时间戳（时间戳回答的是
--     「什么时候首次确认的」，被重复点击覆盖就失去意义）。
--
-- 形状：
--   PK (USER_OID) —— 一个账号一行，重复确认是 no-op（MERGE 的 WHEN NOT MATCHED
--   分支），并发下也只可能有一行。
--   没有 OID 列：这行没有独立身份，不会被别的对象引用。
--   没有外键：用户可能被硬删除，而这行是用户数据、不是审计材料（与
--   NOTIFICATION_READS 同口径）；用户删了留下的一行是孤儿，但不影响任何判定
--   ——新用户拿到的是新的 OID，读不到旧行。
--
-- 执行：本文件只入库，不会自动执行（应用启动不跑 DDL）。生产在发版窗口用
--   python misc/apply_ddl.py v054
-- 手工执行（--dry-run 只解析不连库）。
--
-- 前置：无（不依赖任何既有对象）。注意后端必须**先**上表再发新版本：新接口
-- 会读写这张表，表不存在时表现为 ORA-00942 → 500。
--
-- 回滚：
--   DROP TABLE ai_agent_acks;   -- 只丢「已确认」标记，警示会重新弹出
--
-- 幂等性：同 V024 起的惯例 —— CREATE TABLE 吞 ORA-00955（对象已存在 = 重跑），
-- 其它错误照常 RAISE。
-- ============================================================================

BEGIN
  EXECUTE IMMEDIATE '
CREATE TABLE ai_agent_acks (
  user_oid VARCHAR2(24 CHAR) NOT NULL,
  acked_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  PRIMARY KEY (user_oid)
)';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN RAISE; END IF;
END;
/
